"""
karaoke_ass.py - Advanced SubStation Alpha (.ass) generator for word-level animated & karaoke subtitles.
Supports Alex Hormozi/Reels bouncy styles, active word highlights, and smooth karaoke timing tags.
"""

from typing import List, Dict, Any, Optional
import math


def format_ass_time(seconds: float) -> str:
    """Format seconds into ASS timestamp format: H:MM:SS.cc (centiseconds)."""
    if seconds < 0:
        seconds = 0.0
    h = int(seconds // 3600)
    m = int((seconds % 3600) // 60)
    s = int(seconds % 60)
    cs = int(round((seconds - int(seconds)) * 100))
    if cs >= 100:
        cs = 99
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def escape_ass_text(text: str) -> str:
    """Escape braces and control characters in ASS text."""
    return text.replace("{", "(").replace("}", ")")


def generate_karaoke_ass(
    cards: List[Dict[str, Any]],
    script_title: str = "Hinglish Subtitles - Karaoke",
    play_res_x: int = 1080,
    play_res_y: int = 1920,
    font_name: str = "Montserrat ExtraBold",
    font_size: int = 68,
    primary_color: str = "&H00FFFFFF",    # White (ABGR)
    secondary_color: str = "&H0000C7FF",  # Yellow Highlight #FFC700 (BGR)
    outline_color: str = "&H00000000",    # Pure Black outline
    back_color: str = "&H80000000",       # Semi-transparent shadow
    outline_width: int = 4,
    shadow_depth: int = 2,
    margin_v: int = 240,                  # Vertical offset from bottom (Reels safe zone)
    use_hinglish: bool = True
) -> str:
    """
    Generate complete .ass subtitle script with word-level karaoke timing tags (\\k).
    
    In ASS:
    - PrimaryColour is the base inactive word color (White).
    - SecondaryColour is the highlighted karaoke active word color (Yellow/Neon).
    - {\\k<centiseconds>} tells the renderer how long each word stays highlighted.
    """
    header = f"""[Script Info]
; Script generated by Hinglish Subtitles Studio v2.5
Title: {script_title}
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: {play_res_x}
PlayResY: {play_res_y}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{font_name},{font_size},{primary_color},{secondary_color},{outline_color},{back_color},-1,0,0,0,100,100,1,0,1,{outline_width},{shadow_depth},2,40,40,{margin_v},1
Style: HormoziYellow,{font_name},{font_size + 4},&H00FFFFFF,&H0000C7FF,&H00000000,&H90000000,-1,0,0,0,100,100,2,0,1,5,3,2,40,40,{margin_v},1
Style: CyanPop,{font_name},{font_size + 4},&H00FFFFFF,&H00F8BD38,&H00000000,&H90000000,-1,0,0,0,100,100,2,0,1,5,3,2,40,40,{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

    dialogue_lines = []

    for card in cards:
        card_start = card.get("start", 0.0)
        card_end = card.get("end", card_start + 2.0)
        start_str = format_ass_time(card_start)
        end_str = format_ass_time(card_end)

        words = card.get("words", [])
        if not words:
            # Fallback if no word tokens: display card text
            text = card.get("hinglish_text" if use_hinglish else "original_text", "")
            dialogue_lines.append(f"Dialogue: 0,{start_str},{end_str},HormoziYellow,,0,0,0,,{escape_ass_text(text)}")
            continue

        # Build karaoke dialogue line with {\k<centiseconds>} tags
        karaoke_parts = []
        cur_t = card_start

        for idx, w in enumerate(words):
            w_start = w.get("start", cur_t)
            w_end = w.get("end", w_start + 0.3)
            w_text = w.get("hinglish" if use_hinglish else "word", "")
            
            # Duration in centiseconds
            dur_cs = max(1, int(round((w_end - w_start) * 100)))
            
            # Handle potential small leading gap before first word
            if idx == 0 and w_start > card_start:
                lead_cs = int(round((w_start - card_start) * 100))
                if lead_cs > 0:
                    karaoke_parts.append(f"{{\\k{lead_cs}}}")

            clean_word = escape_ass_text(w_text).strip()
            if clean_word:
                # Add trailing space for word separation
                karaoke_parts.append(f"{{\\k{dur_cs}}}{clean_word} ")
            
            cur_t = w_end

        dialogue_text = "".join(karaoke_parts).strip()
        dialogue_lines.append(f"Dialogue: 0,{start_str},{end_str},HormoziYellow,,0,0,0,,{dialogue_text}")

    return header + "\n".join(dialogue_lines) + "\n"
